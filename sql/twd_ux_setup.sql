-- Run once in the Supabase SQL Editor for TWD production before deploying app_prod.py.
-- This installs one metadata table, one private Storage bucket, and two atomic due-date functions.
begin;

create table if not exists public.twd_case_documents (
    id bigint generated by default as identity primary key,
    issue_id text not null,
    category text not null check (category in ('issue_report', 'vendor_reply', 'qav_review')),
    file_name text not null check (char_length(file_name) between 1 and 255),
    object_path text not null unique,
    content_type text not null,
    size_bytes bigint not null check (size_bytes between 1 and 10485760),
    sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
    idempotency_key text not null unique,
    created_at timestamptz not null default now()
);

create index if not exists twd_case_documents_issue_created_idx
    on public.twd_case_documents (issue_id, created_at desc);

alter table public.twd_case_documents enable row level security;
revoke all on table public.twd_case_documents from anon, authenticated;
grant select, insert on table public.twd_case_documents to service_role;
grant usage, select on sequence public.twd_case_documents_id_seq to service_role;

-- A QAV initial due-date setting has no previous date; keep that audit value NULL.
alter table public.twd_due_date_extension_requests
    alter column current_due_date drop not null;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
    'twd-case-documents-prod', 'twd-case-documents-prod', false, 10485760,
    array[
        'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        'application/vnd.ms-excel', 'text/csv', 'application/pdf',
        'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
    ]
)
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

create or replace function public.twd_qav_review_due_date_extension(
    p_request_id bigint,
    p_decision text,
    p_review_note text,
    p_reviewed_by text
)
returns table(issue_id text, status text, due_date date)
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
    r public.twd_due_date_extension_requests%rowtype;
    v_current_due date;
    v_count integer;
begin
    if p_decision not in ('核准', '駁回') then
        raise exception 'Decision must be 核准 or 駁回';
    end if;

    select * into r
    from public.twd_due_date_extension_requests
    where id = p_request_id and twd_due_date_extension_requests.status = '待QAV核准'
    for update;
    if not found then
        raise exception '展延申請不存在或已由其他人處理';
    end if;

    select nullif(i.due_date::text, '')::date into v_current_due
    from public.issues_prod as i
    where i.issue_id = r.issue_id
    for update;
    if not found then
        raise exception '找不到對應案件';
    end if;

    if p_decision = '核准' then
        if v_current_due is distinct from r.current_due_date then
            raise exception '正式期限在申請後已改變；請確認最新日期後再處理申請';
        end if;
        update public.issues_prod as i
        set due_date = r.requested_due_date,
            updated_date = to_char(now() at time zone 'Asia/Taipei', 'YYYY-MM-DD HH24:MI')
        where i.issue_id = r.issue_id;
        get diagnostics v_count = row_count;
        if v_count <> 1 then
            raise exception '案件 Due date 更新筆數非 1';
        end if;
    end if;

    update public.twd_due_date_extension_requests
    set status = p_decision,
        review_note = p_review_note,
        reviewed_by = p_reviewed_by,
        reviewed_at = now()
    where id = p_request_id and twd_due_date_extension_requests.status = '待QAV核准';
    get diagnostics v_count = row_count;
    if v_count <> 1 then
        raise exception '展延申請審核狀態更新筆數非 1';
    end if;

    return query select r.issue_id, p_decision, case when p_decision = '核准' then r.requested_due_date else v_current_due end;
end;
$$;

revoke all on function public.twd_qav_review_due_date_extension(bigint, text, text, text) from public, anon, authenticated;
grant execute on function public.twd_qav_review_due_date_extension(bigint, text, text, text) to service_role;

create or replace function public.twd_qav_set_due_date(
    p_issue_id text,
    p_new_due_date date,
    p_reason text,
    p_reviewed_by text
)
returns table(issue_id text, due_date date)
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
    v_current_due date;
    v_count integer;
begin
    if char_length(trim(coalesce(p_reason, ''))) = 0 then
        raise exception '調整原因不可空白';
    end if;
    if p_new_due_date is null or p_new_due_date < (now() at time zone 'Asia/Taipei')::date then
        raise exception '新 Due date 不可早於今天';
    end if;

    select nullif(i.due_date::text, '')::date into v_current_due
    from public.issues_prod as i
    where i.issue_id = p_issue_id
    for update;
    if not found then
        raise exception '找不到對應案件';
    end if;
    if exists (
        select 1 from public.twd_due_date_extension_requests
        where twd_due_date_extension_requests.issue_id = p_issue_id
          and twd_due_date_extension_requests.status = '待QAV核准'
    ) then
        raise exception '此案件已有待核准展延申請；請先處理該申請';
    end if;
    if v_current_due is not distinct from p_new_due_date then
        raise exception '新 Due date 與目前期限相同';
    end if;

    update public.issues_prod as i
    set due_date = p_new_due_date,
        updated_date = to_char(now() at time zone 'Asia/Taipei', 'YYYY-MM-DD HH24:MI')
    where i.issue_id = p_issue_id;
    get diagnostics v_count = row_count;
    if v_count <> 1 then
        raise exception '案件 Due date 更新筆數非 1';
    end if;

    insert into public.twd_due_date_extension_requests (
        issue_id, current_due_date, requested_due_date, reason,
        requested_by, status, request_type, review_note, reviewed_by, reviewed_at
    ) values (
        p_issue_id, v_current_due, p_new_due_date, trim(p_reason),
        p_reviewed_by, '核准', case when v_current_due is null then 'QAV直接設定' else 'QAV直接調整' end,
        trim(p_reason), p_reviewed_by, now()
    );

    return query select p_issue_id, p_new_due_date;
end;
$$;

revoke all on function public.twd_qav_set_due_date(text, date, text, text) from public, anon, authenticated;
grant execute on function public.twd_qav_set_due_date(text, date, text, text) to service_role;
commit;
